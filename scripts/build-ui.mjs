import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=path.join(root,'ui');
const read=name=>fs.readFileSync(path.join(source,name),'utf8');

// Scripts/styles stay self-contained. Approved Figma character SVGs are local
// image assets, shared by the file preview and the runtime's ui/assets folder.
export function buildUI({check=false}={}) {
  const manifest=JSON.parse(read('styles/manifest.json'));
  const metrics=JSON.parse(read('tokens/collection.json'));
  for(const [name,value] of Object.entries(metrics))if(!Number.isFinite(value)||value<=0)throw new Error(`Invalid metric ${name}`);
  const metricCSS=':root {\n'+Object.entries(metrics).filter(([name])=>name!=='visibleCards').map(([name,value])=>'  --collection-'+name.replace(/[A-Z]/g,c=>'-'+c.toLowerCase())+': '+value+'px;').join('\n')+'\n}\n';
  const styles=name=>manifest[name].map(file=>`/* ${file} */\n${read(file)}`).join('\n');
  const replace=(text,marker,value)=>{
    if(text.split(marker).length!==2)throw new Error(`Expected exactly one ${marker}`);
    return text.replace(marker,()=>value);
  };
  const companionAssetBase=`function companionAssetUrl(name) {
    const inRuntimeUI=/\\/ui\\/[^/]+\\.html$/.test(location.pathname);
    const relative=(inRuntimeUI?'assets/companion/':'ui/assets/companion/')+name;
    try{return new URL(relative,document.baseURI).href;}catch{return relative;}
  }`;
  const companionAssets=Object.fromEntries(JSON.parse(read('assets/companion/manifest.json')).assets.map(({file})=>[
    file,'data:image/svg+xml;base64,'+fs.readFileSync(path.join(source,'assets/companion',file)).toString('base64'),
  ]));
  const standaloneAssetBase=`const companionAssets=${JSON.stringify(companionAssets)};\nfunction companionAssetUrl(name){return companionAssets[name]||'';}`;
  const companionSources=(text,{standalone=false}={})=>{
    text=replace(text,'/* @tuotie:companion-asset-base */',standalone?standaloneAssetBase:companionAssetBase);
    text=replace(text,'/* @tuotie:companion-components */',read('components/companion.js'));
    return replace(text,'/* @tuotie:companion-motion */',read('components/companion-motion.js'));
  };
  let html=replace(read('templates/catalog.html'),'/* @tuotie:styles */',styles('catalog')+'\n'+metricCSS);
  html=companionSources(html);
  html=replace(html,'/* @tuotie:content-components */',read('components/content-card.js'));
  html=replace(html,'/* @tuotie:task-components */',read('components/task-panel.js'));
  html=html.replace('<!doctype html>','<!doctype html>\n<!-- Generated by scripts/build-ui.mjs from ui/. Do not edit this artifact. -->');
  let overlay=replace(read('desktop-overlay.js'),'/* @tuotie:collection-metrics */ {}',JSON.stringify(metrics));
  overlay=replace(overlay,'/* @tuotie:collection-controller */',read('components/collection-controller.js'));
  overlay=replace(overlay,'/* @tuotie:collection-hover */',read('components/collection-hover.js'));
  overlay=replace(overlay,'/* @tuotie:pack-drag-motion */',read('components/pack-drag-motion.js'));
  for(const name of ['desktop','collection'])overlay=replace(overlay,`/* @tuotie:${name}-styles */ ''`,JSON.stringify(styles(name)));
  overlay='// Generated by scripts/build-ui.mjs from ui/. Do not edit this artifact.\n'+overlay;
  let motionPreview=replace(read('templates/companion-motion-preview.html'),'/* @tuotie:styles */',[
    'styles/tokens/palette.css','styles/foundation.css','styles/components/companion-character.css',
  ].map(file=>read(file)).join('\n'));
  // A review link may open in an isolated file viewer or be copied alone.
  // Pre-render the real component and embed unchanged SVG bytes so even a
  // script-disabled preview displays the character without sibling files.
  const staticCompanion=vm.runInNewContext(read('components/companion.js')+';companionMarkup',{
    companionAssetUrl:name=>companionAssets[name]||'',
  });
  motionPreview=replace(motionPreview,'<!-- @tuotie:companion-large -->',staticCompanion({id:'mpLarge',className:'orb',pose:'working'}));
  motionPreview=replace(motionPreview,'<!-- @tuotie:companion-actual -->',staticCompanion({id:'mpActual',className:'orb',pose:'working'}));
  motionPreview=companionSources(motionPreview,{standalone:true});
  motionPreview=motionPreview.replace('<!doctype html>','<!doctype html>\n<!-- Generated by scripts/build-ui.mjs from ui/. Do not edit this artifact. -->');
  const outputs={'components-preview.html':html,'desktop-preview/desktop-overlay.js':overlay,'companion-motion-preview.html':motionPreview};
  const stale=[];
  for(const [name,content] of Object.entries(outputs)) {
    const file=path.join(root,name);
    if(fs.existsSync(file)&&fs.readFileSync(file,'utf8')===content)continue;
    stale.push(name);
    if(!check)fs.writeFileSync(file,content);
  }
  if(check&&stale.length)throw new Error('UI artifacts need rebuilding: '+stale.join(', '));
  return Object.keys(outputs);
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  buildUI({check:process.argv.includes('--check')});
  console.log(process.argv.includes('--check')?'UI artifacts are current.':'Built UI components.');
}
